"""Export our instances to pyDCOP's YAML format (issue #5).

Two choices work around problems in pyDCOP's MGM (see README.md); neither changes the cost model,
which check 1 verifies on 2,000 timetables:
  * the unary cost is a one-variable extensional constraint, not a variable cost_function: MGM's
    value choice (_compute_best_value -> find_arg_optimal) ignores a variable's cost_function;
  * an exam with no shared students gets a zero-cost "link" constraint with another exam of its own
    department: MGM gives a variable without neighbours a random final value in on_start, ignoring its
    unary constraint, while a variable with a neighbour goes through the normal MGM rounds.

Runs in the project environment (standard library + vmgm only; no PyYAML needed):

    python -m validation.pydcop.export

For the loose family, seeds 100-119, writes into validation/pydcop/instances/:

  loose_<seed>.yaml       the DCOP:
                            * one variable x_<e> per exam, domain 0..S-1, initial value = our random
                              start M.random_start(inst, 1000 + seed) (the start of our honest MGM),
                            * one unary extensional constraint g_<e> with the preference costs g[e],
                            * one binary extensional constraint n_<e>_<f> per pair with c shared
                              students, whose table is generated by calling vmgm.model.pc(a, b, c),
                            * one all-zero binary constraint link_<e>_<f> for each exam e with no
                              shared students (f = the next exam of the same department),
                            * one agent d<i> per department, objective min.
  loose_<seed>_dist.yaml  the distribution: agent d<i> hosts the variables of its own exams
                          (inst['owner'][e] == i), i.e. department = agent, exam = variable.
"""
import os

from vmgm import model as M

FAMILY = 'loose'
SEEDS = range(100, 120)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'instances')


def instance(seed):
    return M.make_instance(seed, **M.FAMILIES[FAMILY])


def start(inst, seed):
    return M.random_start(inst, 1000 + seed)


def var(e):
    return f'x_{e}'


def agent(i):
    return f'd{i}'


def isolated_links(inst):
    """(e, f) for every exam e that shares no students: f is the next exam of e's department."""
    out = []
    for e in range(inst['E']):
        if not inst['adj'][e]:
            own = inst['exams'][inst['owner'][e]]
            out.append((e, own[(own.index(e) + 1) % len(own)]))
    return out


def dcop_yaml(inst, seed):
    S, x0 = inst['S'], start(inst, seed)
    lines = [f'name: {FAMILY}_{seed}', 'objective: min', '',
             'domains:', '  slots:', '    values: [' + ', '.join(str(a) for a in range(S)) + ']', '',
             'variables:']
    for e in range(inst['E']):
        lines += [f'  {var(e)}:', '    domain: slots', f'    initial_value: {x0[e]}']
    lines += ['', 'constraints:']
    for e in range(inst['E']):                                   # unary: preference cost g_e(slot)
        by_cost = {}
        for a in range(S):
            by_cost.setdefault(inst['g'][e][a], []).append(str(a))
        lines += [f'  g_{e}:', '    type: extensional', f'    variables: {var(e)}', '    values:']
        lines += [f'      {cost}: "{" | ".join(slots)}"' for cost, slots in sorted(by_cost.items())]
    for e, f in isolated_links(inst):                            # zero cost: only gives e a neighbour
        lines += [f'  link_{e}_{f}:', '    type: extensional', f'    variables: [{var(e)}, {var(f)}]',
                  '    default: 0', '    values: {}']
    for (e, f), c in sorted(inst['n'].items()):                  # binary: pc(a, b, c), default 0
        by_cost = {}
        for a in range(S):
            for b in range(S):
                cost = M.pc(a, b, c)
                if cost:
                    by_cost.setdefault(cost, []).append(f'{a} {b}')
        lines += [f'  n_{e}_{f}:', '    type: extensional', f'    variables: [{var(e)}, {var(f)}]',
                  '    default: 0', '    values:']
        lines += [f'      {cost}: "{" | ".join(pairs)}"' for cost, pairs in sorted(by_cost.items())]
    lines += ['', 'agents: [' + ', '.join(agent(i) for i in range(inst['N'])) + ']', '']
    return '\n'.join(lines)


def dist_yaml(inst):
    lines = ['distribution:']
    for i in range(inst['N']):
        exams = [e for e in range(inst['E']) if inst['owner'][e] == i]
        lines.append(f'  {agent(i)}: [' + ', '.join(var(e) for e in exams) + ']')
    return '\n'.join(lines) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    for seed in SEEDS:
        inst = instance(seed)
        with open(os.path.join(OUT, f'{FAMILY}_{seed}.yaml'), 'w') as fh:
            fh.write(dcop_yaml(inst, seed))
        with open(os.path.join(OUT, f'{FAMILY}_{seed}_dist.yaml'), 'w') as fh:
            fh.write(dist_yaml(inst))
    print(f'wrote {2 * len(SEEDS)} files to {OUT}')


if __name__ == '__main__':
    main()
